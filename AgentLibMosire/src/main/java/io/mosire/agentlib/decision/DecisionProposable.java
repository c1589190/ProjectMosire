package io.mosire.agentlib.decision;

/**
 * 工具声明「我可以被提议进决策包」（设计 §5.9 ①；可提议面的<b>唯一</b>声明点）。
 *
 * <p><b>实现它 ⇒ 进可提议面；不实现 ⇒ 不进。</b>判定形态只有 {@code instanceof} 一个取值，没有第三态：装配期的可提议面审计 （设计 §4.6 / §6
 * 的「可提议 ⊆ 可调用」对账）读的也是同一个标记。
 *
 * <p><b>★ 为什么刻意是空接口</b>：隔壁（SimulatorMosire 的 {@code DecisionProposable}）在这条声明上还挂着 {@code
 * skipKeys()} / {@code createsUnit()} 两个方法，那是<b>目标提取</b>的领域旋钮——「新单位 id 不是既有资源、
 * 不能按『将要成为的目标』判越界」是<b>宿主</b>的业务知识。AgentLib 是通用层，它只回答一个问题： <b>这个工具能不能进包</b>（一个
 * bit）。多一个方法就多一处「第二处真相」：通用层一旦开始理解「哪个参数是要提取的目标」， 就成了第二个业务口径的维护点，而每个宿主的提取语义并不相同（有的提单位、有的提关系、有的什么都不提）。
 * 所以领域旋钮留在宿主的实现类里（隔壁自己那份接口与审计收口），本接口只留一个 {@code instanceof} 判据。
 *
 * <p><b>它不是权限</b>：实现本接口<b>不</b>放行任何调用——可提议面 ⊆ 可调用面（设计 §6）。进包之前，提议面仍要逐条过 {@code
 * ItemValidator}（工具名级权限 / 资源面准入 / 角色，宿主注入），执行时仍要过单条闸链 （{@code
 * ToolCallAuthorizer}）。本标记只加一层<b>收窄</b>：它绝不使一个本来调不动的工具变得可调。
 */
public interface DecisionProposable {}
