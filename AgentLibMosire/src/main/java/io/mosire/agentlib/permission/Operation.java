package io.mosire.agentlib.permission;

/**
 * 一次资源访问的<b>操作</b>（S5-C）：{@code READ} 或 {@code WRITE}，不多不少。
 *
 * <p><b>为什么不给更多档</b>（{@code EXECUTE}/{@code DELETE}/{@code LIST} 之类）：每多一档，每个命名空间的策略、每个调用者的
 * 表态、每条拒因都得再解释一遍——"策略 × 操作"每加一行就多一处可以自相矛盾的地方，而今天真实存在的只有两问："能不能碰"与
 * "能不能改"。将来真要细分时，加档必须连带回答"谁的缺省策略把它算作读"，不能默默多一个取值。
 *
 * <p><b>与工具白名单无关</b>：那是"这个工具能不能用"（{@link AccessToken} + {@code AgentPermissionSet} 的工具名级维度），
 * 本枚举只管"用这个工具碰哪块资源、能碰还是能改"。
 */
public enum Operation {
  /** 读取：不改变资源内容/状态的访问。 */
  READ,

  /**
   * 写入：改变资源内容/状态的访问。<b>含创建与删除</b>——"改"只有一档，细分留给工具作者（它可以在自己内部再设槛），
   * 而不是在这里造出"删比写更危险"的判定表（那需要工具自己来定义，SPI 不替它猜）。
   */
  WRITE
}
