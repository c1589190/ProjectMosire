package io.mosire.agentlib.permission;

/**
 * 工具对自己声明的命名空间给出的<b>缺省策略</b>（S5-C；设计 §2.5 的三个取值）。
 *
 * <p><b>"缺省"不是"封顶"</b>：调用者显式对同一命名空间表了态（权限集第 7 维 {@link ResourceScopeMap} 里有这一项）时，以调用者的
 * 表态为准，本策略退场。这与 {@link ResourceScopeMap} 的层语义同源（"未声明 = 本层不表态 ⇒ 回落下一层"），也正是设计 §2.5.3 "缺省值 = 工具的
 * {@code ResourceManifest} 默认"的字面意思。
 *
 * <p><b>为什么不能做成封顶（诚实记录一处取舍）</b>：若工具的策略能压过调用者的显式授权，那"插件数据面"就出现了死结——调用者 （子 Agent 配置）明明被授予了某块区域，插件一句
 * {@code DENY} 就让它永远够不着，而调用者侧没有任何办法解开（只能改插件代码）。 于是"谁能碰插件数据"这件事被搬进了插件源码，恰恰违背本 SPI 的目的（由配置面决定可达面）。
 *
 * <p><b>代价（写在这里，不藏）</b>：工具想表达"这个命名空间无论如何都不许写"时今天拿不到这种封顶；只能退一步用 {@link
 * #READ_ONLY}（未表态者只给读），或由调用者侧把它配成 {@link ResourceScope#none()}（显式"哪里都不许"）。真需要封顶时它是一个新的 判定维（"工具硬约束"
 * × "调用者授权" 的求交），必须连同 {@code isSubset} 一起设计，不能靠改这里的语义偷渡。
 */
public enum ResourcePolicy {
  /** 全放：调用者未表态时，该命名空间内读写皆可。 */
  UNRESTRICTED,

  /** 只读（工具作者应当优先选它）：调用者未表态时读放行、写拒绝。 */
  READ_ONLY,

  /** 拒：调用者未表态时，该命名空间里什么都别想碰（fail-closed 的缺省，插件类工具应当用它）。 */
  DENY
}
